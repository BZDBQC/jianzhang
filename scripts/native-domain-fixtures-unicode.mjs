import { writeFileSync } from 'node:fs';

const unicodeVersion='17.0';
if(process.versions.unicode!==unicodeVersion){
  throw new Error(`Use a Node runtime with Unicode ${unicodeVersion}; found ${process.versions.unicode}`);
}

// Pin the legacy JS runtime's full, locale-neutral lowercase and context properties.
// Unicode SpecialCasing defines U+0130 expansion and Final_Sigma:
// https://www.unicode.org/Public/17.0.0/ucd/SpecialCasing.txt
const lower = [];
const cased = [];
const ignorable = [];
for (let code = 0; code <= 0x10ffff; code++) {
  if (code >= 0xd800 && code <= 0xdfff) continue;
  const char = String.fromCodePoint(code);
  const folded = char.toLowerCase();
  if (char !== folded) lower.push(`${code.toString(16)}:${[...folded].map(c => c.codePointAt(0).toString(16)).join(',')}`);
  if (/\p{Cased}/u.test(char)) cased.push(code);
  if (/\p{Case_Ignorable}/u.test(char)) ignorable.push(code);
}
function ranges(values) {
  const result=[];
  for(let i=0;i<values.length;i++) {
    const start=values[i];
    let end=start;
    while(values[i+1]===end+1) end=values[++i];
    result.push(`${start.toString(16)}:${end.toString(16)}`);
  }
  return result;
}
function packed(name, values) {
  const lines=[];
  for(let i=0;i<values.length;i+=10) lines.push(`  '${values.slice(i,i+10).join(';')};'`);
  return `const ${name} =\n${lines.join('\n')};\n`;
}
writeFileSync('clients/flutter/lib/domain/unicode_case_data.dart',
  `// Generated by scripts/native-domain-fixtures-unicode.mjs; Unicode ${process.versions.unicode}.\n// Source: Unicode SpecialCasing, pinned to the legacy JavaScript contract.\n\n`+
  packed('lowercaseMappings',lower)+packed('casedRanges',ranges(cased))+packed('caseIgnorableRanges',ranges(ignorable)));
const samples=['ΟΣ','Ο\u0301Σ','Σ','ΑΣΑ','Α\u0345Σ\u0301','AΣ\u0301B','İ','İSTANBUL','ÉCOLE','\u{1e900}','ΣΣ','ΑΣ\u0027'];
writeFileSync('tests/fixtures/native-unicode-v1.json',JSON.stringify({unicode:process.versions.unicode,samples:samples.map(value=>({value,lower:value.toLowerCase()}))},null,2)+'\n');
console.log(`Generated ${lower.length} full lowercase mappings and Unicode context ranges`);
