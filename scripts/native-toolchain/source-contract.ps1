function Assert-NoReparsePath {
  param([string]$Path,[ValidateSet('Directory','File','Any')][string]$PathType='Directory',[switch]$AllowMissing)
  $absolute=[IO.Path]::GetFullPath($Path)
  $volume=[IO.Path]::GetPathRoot($absolute)
  $parts=@($absolute.Substring($volume.Length).TrimEnd('\','/').Split([char[]]@('\','/'),[StringSplitOptions]::RemoveEmptyEntries))
  $current=$volume
  $nodes=@($volume)
  foreach($part in $parts) { $current=Join-Path $current $part; $nodes += $current }
  for($index=0;$index -lt $nodes.Count;$index++) {
    $errors=@()
    $item=Get-Item -LiteralPath $nodes[$index] -Force -ErrorAction SilentlyContinue -ErrorVariable errors
    if(!$item) {
      foreach($failure in $errors) { if($failure.CategoryInfo.Category -ne [Management.Automation.ErrorCategory]::ObjectNotFound) { throw $failure } }
      if($AllowMissing) { return $absolute }
      throw "Required path does not exist: $($nodes[$index])"
    }
    if($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Path contains a reparse point: $($nodes[$index])" }
    $expected=if($index -lt $nodes.Count-1) { 'Directory' } else { $PathType }
    if(($expected -eq 'Directory' -and !$item.PSIsContainer) -or ($expected -eq 'File' -and $item.PSIsContainer)) { throw "Path has the wrong type ($expected required): $($nodes[$index])" }
  }
  return $absolute
}
function Assert-WorkspacePath {
  param([string]$Workspace,[string]$Path,[ValidateSet('Directory','File','Any')][string]$PathType='Directory',[switch]$AllowMissing)
  $owned=(Assert-NoReparsePath -Path $Workspace).TrimEnd('\','/')
  $absolute=[IO.Path]::GetFullPath($Path)
  if($absolute -ne $owned -and !$absolute.StartsWith($owned+[IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase)) { throw "Path is outside its owning workspace: $absolute" }
  return Assert-NoReparsePath -Path $absolute -PathType $PathType -AllowMissing:$AllowMissing
}
function Get-TreeFiles {
  param([string]$Root, [string[]]$Skip = @())
  $Root = (Assert-NoReparsePath -Path $Root).TrimEnd('\','/')
  $pending = [Collections.Generic.Stack[string]]::new()
  $pending.Push($Root)
  $files = [Collections.Generic.SortedDictionary[string,object]]::new([StringComparer]::Ordinal)
  while ($pending.Count) {
    foreach ($item in Get-ChildItem -LiteralPath $pending.Pop() -Force) {
      $relative = $item.FullName.Substring($Root.Length+1).Replace('\','/')
      $ignored = $false
      foreach ($prefix in $Skip) { if ($relative -eq $prefix -or $relative.StartsWith($prefix+'/',[StringComparison]::Ordinal)) { $ignored=$true; break } }
      if ($ignored) { continue }
      if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Input contains a reparse point: $relative" }
      if ($item.PSIsContainer) { $pending.Push($item.FullName) } else { $files.Add($relative,$item) }
    }
  }
  return $files.Values
}
function Get-ClientSourceFiles {
  param([string]$Root, [ValidateSet('windows','android')][string]$Platform)
  $skip = @('build','.qa','.idea','.git','.vscode','test','integration_test','packaging','linux','macos','ios','web')
  if ($Platform -eq 'windows') { $skip += @('android','windows/flutter/ephemeral') }
  else {
    # These files are generated by the selected Flutter SDK, not handwritten
    # Android inputs. Release tooling regenerates them from the locked packages.
    $skip += @('windows','.dart_tool','.flutter-plugins-dependencies','android/.gradle','android/build','android/app/build','android/local.properties','android/app/src/main/java/io/flutter/plugins/GeneratedPluginRegistrant.java')
  }
  $files = @(Get-TreeFiles -Root $Root -Skip $skip | Where-Object {
    $relative=$_.FullName.Substring([IO.Path]::GetFullPath($Root).TrimEnd('\','/').Length+1).Replace('\','/')
    !$relative.StartsWith('.dart_tool/') -or $relative -in @('.dart_tool/package_config.json','.dart_tool/package_graph.json')
  })
  return $files | Where-Object { $_.Name -ne '.flutter-plugins' -and $_.Name -notmatch '^(README|CHANGELOG)\.md$' }
}
function Get-FileListContract {
  param([string]$Root, [object[]]$Files)
  $Root=[IO.Path]::GetFullPath($Root).TrimEnd('\','/')
  $entries=@($Files | ForEach-Object { [pscustomobject]@{path=$_.FullName.Substring($Root.Length+1).Replace('\','/');bytes=$_.Length;sha256=(Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant()} })
  $canonical=($entries | ForEach-Object { $_.path + "`t" + $_.bytes + "`t" + $_.sha256 }) -join "`n"
  $hasher=[Security.Cryptography.SHA256]::Create()
  try { $digest=[BitConverter]::ToString($hasher.ComputeHash([Text.Encoding]::UTF8.GetBytes($canonical))).Replace('-','').ToLowerInvariant() } finally { $hasher.Dispose() }
  return [pscustomobject]@{sha256=$digest;files=$entries}
}
function Get-ClientSourceContract {
  param([string]$Root,[ValidateSet('windows','android')][string]$Platform)
  return Get-FileListContract -Root $Root -Files @(Get-ClientSourceFiles -Root $Root -Platform $Platform)
}
function Get-AndroidMetadataContract {
  param([string]$Root,[switch]$IncludeRegistrant)
  $paths=@('.dart_tool/package_config.json','.dart_tool/package_graph.json','.flutter-plugins-dependencies')
  if($IncludeRegistrant) { $paths += 'android/app/src/main/java/io/flutter/plugins/GeneratedPluginRegistrant.java' }
  $files=@($paths | Sort-Object -CaseSensitive | ForEach-Object {
    $path=Assert-WorkspacePath -Workspace $Root -Path (Join-Path $Root $_) -PathType File
    Get-Item -LiteralPath $path -Force
  })
  return Get-FileListContract -Root $Root -Files $files
}
function Get-PayloadContract {
  param([string]$Root)
  return Get-FileListContract -Root $Root -Files @(Get-TreeFiles -Root $Root)
}
function Assert-FileContract {
  param($Expected,$Actual,[string]$Description)
  if (!$Expected.sha256 -or $Expected.sha256 -ne $Actual.sha256 -or @($Expected.files).Count -ne @($Actual.files).Count) { throw "$Description differs from its recorded stable file contract." }
  for($index=0;$index -lt @($Expected.files).Count;$index++) {
    $left=$Expected.files[$index]; $right=$Actual.files[$index]
    if ($left.path -cne $right.path -or $left.bytes -ne $right.bytes -or $left.sha256 -ne $right.sha256) { throw "$Description file mismatch: $($right.path)" }
  }
}
function Get-ClientVersion {
  param([string]$Root)
  $text=Get-Content -LiteralPath (Join-Path $Root 'pubspec.yaml') -Raw
  if($text -notmatch '(?m)^version:\s*(\d+\.\d+\.\d+)\+(\d+)\s*$') { throw 'Client pubspec must specify semantic version and build number.' }
  return [pscustomobject]@{version=$Matches[1];versionCode=[int]$Matches[2]}
}
function Assert-FlutterVersion {
  param([string]$FlutterRoot,[object]$Release)
  if(!$Release) { throw 'Official selected Flutter release metadata is required.' }
  $machine=& (Join-Path $FlutterRoot 'bin/flutter.bat') --suppress-analytics --version --machine
  if($LASTEXITCODE -ne 0) { throw "Flutter machine-version command failed: $LASTEXITCODE" }
  $actual=($machine -join "`n") | ConvertFrom-Json
  if($actual.frameworkVersion -ne $Release.version -or $actual.frameworkRevision -ne $Release.hash -or $actual.channel -ne $Release.channel -or !$actual.dartSdkVersion.StartsWith([string]$Release.dart_sdk_version)) { throw 'Installed Flutter SDK version/revision/channel/Dart does not match the selected official release.' }
  return $actual
}
function Assert-WindowsPayload {
  param([string]$Root,[string]$PluginMetadata)
  $required=@('jianzhang.exe','flutter_windows.dll','sqlite3.dll','data/icudtl.dat','data/app.so','data/flutter_assets/NativeAssetsManifest.json')
  $plugins=(Get-Content -LiteralPath $PluginMetadata -Raw | ConvertFrom-Json).plugins.windows
  foreach($plugin in $plugins) {
    if($plugin.native_build -ne $false) { $required += ($plugin.name+'_plugin.dll') }
  }
  # JNI bundles its runtime with a distinct file name instead of a plugin DLL.
  $required=$required | Where-Object { $_ -ne 'jni_plugin.dll' }
  if($plugins | Where-Object { $_.name -eq 'jni' }) { $required += 'dartjni.dll' }
  foreach($relative in $required) { if(!(Test-Path -LiteralPath (Join-Path $Root $relative) -PathType Leaf)) { throw "Windows release payload is missing: $relative" } }
  if(!(Get-ChildItem -LiteralPath (Join-Path $Root 'data/flutter_assets') -File -Recurse)) { throw 'Windows Flutter assets are empty.' }
  $native=(Get-Content -LiteralPath (Join-Path $Root 'data/flutter_assets/NativeAssetsManifest.json') -Raw | ConvertFrom-Json).'native-assets'
  foreach($architecture in $native.PSObject.Properties) {
    foreach($asset in $architecture.Value.PSObject.Properties) {
      if($asset.Value[0] -eq 'absolute') {
        $path=[IO.Path]::GetFullPath((Join-Path $Root $asset.Value[1]))
        if(!$path.StartsWith([IO.Path]::GetFullPath($Root).TrimEnd('\')+'\',[StringComparison]::OrdinalIgnoreCase) -or !(Test-Path -LiteralPath $path -PathType Leaf)) { throw "Missing or external native code asset: $($asset.Name)" }
      }
    }
  }
}
